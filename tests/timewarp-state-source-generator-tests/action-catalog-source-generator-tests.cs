public class Should_Emit_Single_Entry
{
  public static void Given_One_Cataloged_Action()
  {
    const string Source =
      """
      namespace App;

      using TimeWarp.Mediator;
      using TimeWarp.State;

      public sealed partial class CredentialsState : State<CredentialsState>
      {
        public override void Initialize() { }

        public static class AddPasskeyActionSet
        {
          [CatalogAction(Description = "Add a passkey to the account.")]
          public sealed class Action : IAction
          {
            public Action(string label) { Label = label; }
            public string Label { get; }
          }
        }
      }
      """;

    (GeneratorDriverRunResult runResult, Compilation outputCompilation) = ActionCatalogGeneratorTestDriver.Run(Source);

    ActionCatalogGeneratorTestDriver.CatalogSource(runResult).ReplaceLineEndings().ShouldBe
    (
      """
      // <auto-generated/>
      #nullable enable
      #pragma warning disable CS1591

      [assembly: global::Catalog.Tests.GeneratedActionCatalogProviderAttribute]

      namespace Catalog.Tests
      {
        /// <summary>Actions in this assembly marked with [CatalogAction].</summary>
        internal static class GeneratedActionCatalog
        {
          public static global::System.Collections.Generic.IReadOnlyList<global::TimeWarp.State.ActionCatalogEntry> All { get; } =
            new global::TimeWarp.State.ActionCatalogEntry[]
            {
              new global::TimeWarp.State.ActionCatalogEntry
              (
                name: "Credentials.AddPasskey",
                description: "Add a passkey to the account.",
                permissions: global::System.Array.Empty<string>(),
                visibility: (global::TimeWarp.State.ActionVisibility)1,
                stateType: typeof(global::App.CredentialsState),
                actionType: typeof(global::App.CredentialsState.AddPasskeyActionSet.Action),
                parameters: new global::TimeWarp.State.ActionCatalogParameter[]
                {
                  new global::TimeWarp.State.ActionCatalogParameter("label", typeof(string), true, null, "{\"type\":\"string\"}"),
                },
                inputSchema: "{\"type\":\"object\",\"properties\":{\"label\":{\"type\":\"string\"}},\"required\":[\"label\"],\"additionalProperties\":false}",
                executor: static (store, arguments, cancellationToken) =>
                {
                  global::TimeWarp.State.ActionCatalogArguments.EnsureCount("Credentials.AddPasskey", arguments, 1, 1);
                  global::App.CredentialsState state = store.GetState<global::App.CredentialsState>();
                  return state.AddPasskey(global::TimeWarp.State.ActionCatalogArguments.Get<string>("Credentials.AddPasskey", arguments, 0, "label"), externalCancellationToken: cancellationToken);
                },
                displayName: null
              ),
            };
        }

        internal sealed class GeneratedActionCatalogProviderAttribute : global::TimeWarp.State.ActionCatalogProviderAttribute
        {
          public override global::System.Collections.Generic.IReadOnlyList<global::TimeWarp.State.ActionCatalogEntry> Entries => GeneratedActionCatalog.All;
        }
      }
      #pragma warning restore CS1591

      """.ReplaceLineEndings()
    );
    ActionCatalogGeneratorTestDriver.ShouldCompile(outputCompilation);
  }
}

