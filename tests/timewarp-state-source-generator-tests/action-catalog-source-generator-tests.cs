public class Should_Emit_Multiple_Entries
{
  public static void Given_Several_Cataloged_Actions_Only_Opted_In_Are_Listed_In_Name_Order()
  {
    const string Source =
      """
      namespace App;

      using TimeWarp.Mediator;
      using TimeWarp.State;

      public sealed partial class CounterState : State<CounterState>
      {
        public override void Initialize() { }

        public static class ResetActionSet
        {
          [CatalogAction(Description = "Reset the counter.")]
          public sealed class Action : IAction { }
        }

        public static class FetchActionSet
        {
          public sealed class Action : IAction { }
        }
      }

      public sealed partial class ThemeState : State<ThemeState>
      {
        public override void Initialize() { }

        public static class ToggleActionSet
        {
          [CatalogAction(Description = "Toggle dark mode.")]
          public sealed class Action : IAction { }
        }
      }
      """;

    (GeneratorDriverRunResult runResult, Compilation outputCompilation) = ActionCatalogGeneratorTestDriver.Run(Source);
    string generated = ActionCatalogGeneratorTestDriver.CatalogSource(runResult);

    generated.ShouldContain("name: \"Counter.Reset\"");
    generated.ShouldContain("name: \"Theme.Toggle\"");
    generated.ShouldNotContain("Counter.Fetch");
    generated.IndexOf("Counter.Reset", StringComparison.Ordinal)
      .ShouldBeLessThan(generated.IndexOf("Theme.Toggle", StringComparison.Ordinal));
    generated.ShouldContain("return state.Reset(externalCancellationToken: cancellationToken);");
    ActionCatalogGeneratorTestDriver.ShouldCompile(outputCompilation);
  }
}

public class Should_Describe_Parameters
{
  public static void Given_Defaults_Enums_Nullable_And_Complex_Types()
  {
    const string Source =
      """
      namespace App;

      using TimeWarp.Mediator;
      using TimeWarp.State;

      public enum Priority { Low, High }

      public sealed record Command(string Title);

      public sealed partial class TodoState : State<TodoState>
      {
        public override void Initialize() { }

        public static class AddItemActionSet
        {
          [CatalogAction(Description = "Add a todo item.")]
          public sealed class Action : IAction
          {
            public Action(Command command, Priority priority, System.Guid? listId = null, int count = 1)
            {
              Command = command;
            }
            public Command Command { get; }
          }
        }
      }
      """;

    (GeneratorDriverRunResult runResult, Compilation outputCompilation) = ActionCatalogGeneratorTestDriver.Run(Source);
    string generated = ActionCatalogGeneratorTestDriver.CatalogSource(runResult);

    generated.ShouldContain("new global::TimeWarp.State.ActionCatalogParameter(\"command\", typeof(global::App.Command), true, null, null),");
    generated.ShouldContain("new global::TimeWarp.State.ActionCatalogParameter(\"priority\", typeof(global::App.Priority), true, null, \"{\\\"type\\\":\\\"string\\\",\\\"enum\\\":[\\\"Low\\\",\\\"High\\\"]}\"),");
    generated.ShouldContain("new global::TimeWarp.State.ActionCatalogParameter(\"listId\", typeof(global::System.Guid?), false, \"null\", \"{\\\"type\\\":\\\"string\\\",\\\"format\\\":\\\"uuid\\\"}\"),");
    generated.ShouldContain("new global::TimeWarp.State.ActionCatalogParameter(\"count\", typeof(int), false, \"1\", \"{\\\"type\\\":\\\"integer\\\"}\"),");
    generated.ShouldContain("\\\"command\\\":{\\\"x-clr-type\\\":\\\"App.Command\\\"}");
    generated.ShouldContain("\\\"required\\\":[\\\"command\\\",\\\"priority\\\"]");
    generated.ShouldContain("EnsureCount(\"Todo.AddItem\", arguments, 2, 4);");
    generated.ShouldContain("if (arguments.Length == 2) return state.AddItem(");
    generated.ShouldContain("if (arguments.Length == 3) return state.AddItem(");
    generated.ShouldContain("Get<global::System.Guid?>(\"Todo.AddItem\", arguments, 2, \"listId\")");
    ActionCatalogGeneratorTestDriver.ShouldCompile(outputCompilation);
  }
}

