#region Purpose
// DeclaredActionAnalyzer: TWS0015 reports an action a GeneratedRequestPattern declares under a state when the final
// compilation does not contain it (task 160).
#endregion

#region Design
// The analyzer test compilation runs no generator, so a ".g.cs" file plays the other generator's output: present,
// the declared action exists and nothing is reported; absent, TWS0015 fires on the attribute. A request the
// pattern places outside a state is Mediator's business only (TWM013), so State stays silent. {|#0:...|} marks the
// attribute.
#endregion

// ReSharper disable InconsistentNaming
namespace DeclaredActionAnalyzer_;

internal static class DeclaredActionSources
{
  public const string Host =
    """
    namespace App
    {
      using TimeWarp.Mediator;
      using TimeWarp.State;

      public static class DeleteRole { }

      [{|#0:GeneratedRequestPattern("{Host}.{Contract}ActionSet.Action", "{Host}.{Contract}ActionSet.Handler", "TimeWarp.Mediator.IAction", typeof(DeleteRole))|}]
      public sealed partial class RoleState : State<RoleState>
      {
        public override void Initialize() { }
      }
    }
    """;

  public const string Emitted =
    """
    // <auto-generated/>
    namespace App
    {
      partial class RoleState
      {
        public static class DeleteRoleActionSet
        {
          public sealed class Action : global::TimeWarp.Mediator.IAction { }
        }
      }
    }
    """;
}

public class Should_Report_TWS0015
{
  public static async Task Given_Declared_Action_No_Generator_Emitted()
  {
    CSharpAnalyzerTest<DeclaredActionAnalyzer, FixieVerifier> test = AnalyzerTestFactory.Create<DeclaredActionAnalyzer>(DeclaredActionSources.Host);
    test.ExpectedDiagnostics.Add
    (
      new DiagnosticResult(DeclaredActionAnalyzer.DiagnosticId, DiagnosticSeverity.Error)
        .WithLocation(0)
        .WithArguments("App.RoleState", "App.RoleState.DeleteRoleActionSet.Action", "App.RoleState")
    );

    await test.RunAsync();
  }
}

public class Should_Not_Report_TWS0015
{
  public static async Task Given_The_Other_Generator_Emitted_The_Action()
  {
    await AnalyzerTestFactory.Create<DeclaredActionAnalyzer>
    (
      ("RoleState.cs", DeclaredActionSources.Host.Replace("{|#0:", "").Replace(")|}]", ")]")),
      ("RoleState.Contracts.g.cs", DeclaredActionSources.Emitted)
    ).RunAsync();
  }

  public static async Task Given_Request_Not_Under_A_State()
  {
    await AnalyzerTestFactory.Create<DeclaredActionAnalyzer>
    (
      """
      namespace App
      {
        using TimeWarp.Mediator;
        using TimeWarp.State;

        public static class DeleteRole { }

        [GeneratedRequestPattern("{ContractType}.Command", "{ContractType}.Handler", "TimeWarp.Mediator.IAction", typeof(DeleteRole))]
        public sealed partial class RoleState : State<RoleState>
        {
          public override void Initialize() { }
        }
      }
      """
    ).RunAsync();
  }
}
