#region Purpose
// Sample sibling generator: emits <Contract>ActionSet (Action plus Handler) inside each [ContractState] state.
#endregion

#region Design
// TimeWarp.State's and TimeWarp.Mediator's generators cannot see this output. The host declares the same names with
// ContractStateAttribute, which derives from TimeWarp.Mediator.GeneratedRequestPatternAttribute, so Mediator emits a
// Send arm and State emits the dispatch method, catalog entry and manifest row for each Action.
// The Action is a void IAction that carries the contract. The Handler is a StateActionHandler that passes the
// contract to the state's On<Contract> method, which the developer writes (the Handler is nested, so a private method
// is fine). The transform returns the hint name and the text, both strings, so the pipeline stays equatable.
#endregion

namespace Sample09Generator;

[Generator]
public sealed class ContractActionSetGenerator : IIncrementalGenerator
{
  private const string AttributeName = "Sample09Console.ContractStateAttribute";

  public void Initialize(IncrementalGeneratorInitializationContext context)
  {
    IncrementalValuesProvider<(string HintName, string Source)> states = context.SyntaxProvider.ForAttributeWithMetadataName
    (
      AttributeName,
      static (node, _) => node is ClassDeclarationSyntax,
      static (attributeContext, _) => Render(attributeContext)
    );

    context.RegisterSourceOutput(states, static (production, state) => production.AddSource(state.HintName, state.Source));
  }

  private static (string HintName, string Source) Render(GeneratorAttributeSyntaxContext context)
  {
    INamedTypeSymbol state = (INamedTypeSymbol)context.TargetSymbol;
    List<INamedTypeSymbol> contracts = [];
    foreach (AttributeData attribute in context.Attributes)
    {
      foreach (TypedConstant argument in attribute.ConstructorArguments)
      {
        if (argument.Kind != TypedConstantKind.Array) continue;
        contracts.AddRange(argument.Values.Select(value => value.Value).OfType<INamedTypeSymbol>());
      }
    }

    string stateName = state.Name;
    string stateType = state.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    StringBuilder builder = new();
    builder.AppendLine("// <auto-generated/>");
    builder.AppendLine("#nullable enable");
    if (!state.ContainingNamespace.IsGlobalNamespace)
      builder.Append("namespace ").Append(state.ContainingNamespace.ToDisplayString()).AppendLine(";");

    builder.Append("partial class ").AppendLine(stateName);
    builder.AppendLine("{");
    foreach (INamedTypeSymbol contract in contracts)
    {
      string contractType = contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
      builder.Append("  /// <summary>Dispatches the ").Append(contract.Name).AppendLine(" contract.</summary>");
      builder.Append("  public static class ").Append(contract.Name).AppendLine("ActionSet");
      builder.AppendLine("  {");
      builder.AppendLine("    /// <summary>Carries the contract to the Handler.</summary>");
      builder.AppendLine("    public sealed class Action : global::TimeWarp.Mediator.IAction");
      builder.AppendLine("    {");
      builder.AppendLine("      /// <summary>Creates the action.</summary>");
      builder.AppendLine("      /// <param name=\"contract\">The contract.</param>");
      builder.Append("      public Action(").Append(contractType).AppendLine(" contract) => Contract = contract;");
      builder.AppendLine("      /// <summary>The contract.</summary>");
      builder.Append("      public ").Append(contractType).AppendLine(" Contract { get; }");
      builder.AppendLine("    }");
      builder.AppendLine();
      builder.Append("    /// <summary>Passes the contract to the state's On").Append(contract.Name).AppendLine(" method.</summary>");
      builder.AppendLine("    public sealed class Handler : global::TimeWarp.State.StateActionHandler<Action>");
      builder.AppendLine("    {");
      builder.AppendLine("      /// <summary>Creates the handler.</summary>");
      builder.AppendLine("      /// <param name=\"store\">The store.</param>");
      builder.AppendLine("      public Handler(global::TimeWarp.State.IStore store) : base(store) { }");
      builder.AppendLine();
      builder.AppendLine("      /// <inheritdoc />");
      builder.AppendLine("      public override global::System.Threading.Tasks.ValueTask Handle(Action action, global::System.Threading.CancellationToken cancellationToken)");
      builder.AppendLine("      {");
      builder.Append("        Store.GetState<").Append(stateType).Append(">().On").Append(contract.Name).AppendLine("(action.Contract);");
      builder.AppendLine("        return default;");
      builder.AppendLine("      }");
      builder.AppendLine("    }");
      builder.AppendLine("  }");
    }

    builder.AppendLine("}");
    return (stateName + ".ContractActionSets.g.cs", builder.ToString());
  }
}
