#region Purpose
// Emits the State manifest: every state in the assembly and its actions, as one JSON document that DevTools, startup
// checks and other analyzers can read without reflection over members.
#endregion

#region Design
// Output (TimeWarp.State.StateManifest.g.cs): an internal TimeWarpStateManifest with Version and Json constants in the
// sanitized assembly namespace (the catalog's), plus [assembly: TimeWarp.State.StateManifestAttribute(Version, Json)].
// The attribute is public and defined in TimeWarp.State, so it has two readers. At runtime, StateManifest.FromAssembly
// reads the attribute instance, with no member reflection, so it is AOT and trim safe. An analyzer in a consuming
// project reads it from metadata as AttributeData on the referenced assembly symbol.
// Emitted only when the referenced TimeWarp.State defines StateManifestAttribute (AssemblyFact.ManifestAvailable) and
// the assembly declares at least one state, so an older runtime or a state-free assembly gets nothing.
// JSON shape, Version 1 (StateManifest in TimeWarp.State parses it):
//   {"version":1,"assembly":"<AssemblyName>","states":[{"type":"<Type.FullName>","name":"<Type.Name>",
//    "persistent":"SessionStorage"|"LocalStorage"|null,"clone":"generated"|"cloneable",
//    "actions":[{"type":"<Type.FullName>","name":"<telemetry action name>","method":"<State method>"|null,
//      "parameters":[{"name":"amount","type":"int","default":"1"|null,"required":false}],
//      "catalog":"<catalog name>"|null,"tracked":false}]}]}
// States and actions are ordered by type name (ordinal), so the text is stable. The JSON is written by hand: the
// generator targets netstandard2.0 and must not depend on System.Text.Json.
#endregion

namespace TimeWarp.State.SourceGenerator;

internal static class ManifestEmitter
{
  public const string HintName = "TimeWarp.State.StateManifest.g.cs";
  public const string AttributeMetadataName = "TimeWarp.State.StateManifestAttribute";
  public const int Version = 1;

  public static void Emit(ManifestModel? model, SourceProductionContext context)
  {
    if (model is null) return;

    context.AddSource(HintName, GenerateCode(model));
  }

  internal static string GenerateCode(ManifestModel model)
  {
    string json = GenerateJson(model);
    StringBuilder builder = new();
    builder.AppendLine("// <auto-generated/>");
    builder.AppendLine("#nullable enable");
    builder.AppendLine("#pragma warning disable CS1591");
    builder.AppendLine();
    builder.AppendLine($"[assembly: global::TimeWarp.State.StateManifestAttribute(global::{model.NamespaceName}.TimeWarpStateManifest.Version, global::{model.NamespaceName}.TimeWarpStateManifest.Json)]");
    builder.AppendLine();
    builder.AppendLine($"namespace {model.NamespaceName}");
    builder.AppendLine("{");
    builder.AppendLine("  /// <summary>The TimeWarp.State manifest for this assembly: its states and their actions, as JSON.</summary>");
    builder.AppendLine("  internal static class TimeWarpStateManifest");
    builder.AppendLine("  {");
    builder.AppendLine($"    public const int Version = {Version};");
    builder.AppendLine($"    public const string Json = {SymbolDisplay.FormatLiteral(json, quote: true)};");
    builder.AppendLine("  }");
    builder.AppendLine("}");
    builder.AppendLine("#pragma warning restore CS1591");
    return builder.ToString();
  }

  internal static string GenerateJson(ManifestModel model)
  {
    StringBuilder json = new();
    json.Append("{\"version\":").Append(Version);
    json.Append(",\"assembly\":").Append(String(model.AssemblyName));
    json.Append(",\"states\":[");
    bool firstState = true;
    foreach (ManifestStateModel state in model.States)
    {
      if (!firstState) json.Append(',');
      firstState = false;
      json.Append("{\"type\":").Append(String(state.Type));
      json.Append(",\"name\":").Append(String(state.Name));
      json.Append(",\"persistent\":").Append(NullableString(state.Persistent));
      json.Append(",\"clone\":").Append(String(state.CloneKind));
      json.Append(",\"actions\":[");
      bool firstAction = true;
      foreach (ManifestActionModel action in state.Actions)
      {
        if (!firstAction) json.Append(',');
        firstAction = false;
        json.Append("{\"type\":").Append(String(action.Type));
        json.Append(",\"name\":").Append(String(action.Name));
        json.Append(",\"method\":").Append(NullableString(action.Method));
        json.Append(",\"parameters\":[");
        bool firstParameter = true;
        foreach (ManifestParameterModel parameter in action.Parameters)
        {
          if (!firstParameter) json.Append(',');
          firstParameter = false;
          json.Append("{\"name\":").Append(String(parameter.Name));
          json.Append(",\"type\":").Append(String(parameter.Type));
          json.Append(",\"default\":").Append(NullableString(parameter.Default));
          json.Append(",\"required\":").Append(parameter.Required ? "true" : "false");
          json.Append('}');
        }

        json.Append("],\"catalog\":").Append(NullableString(action.Catalog));
        json.Append(",\"tracked\":").Append(action.Tracked ? "true" : "false");
        json.Append('}');
      }

      json.Append("]}");
    }

    json.Append("]}");
    return json.ToString();
  }

  private static string NullableString(string? value) => value is null ? "null" : String(value);

  private static string String(string value)
  {
    StringBuilder builder = new(value.Length + 2);
    builder.Append('"');
    foreach (char character in value)
    {
      switch (character)
      {
        case '"': builder.Append("\\\""); break;
        case '\\': builder.Append("\\\\"); break;
        case '\n': builder.Append("\\n"); break;
        case '\r': builder.Append("\\r"); break;
        case '\t': builder.Append("\\t"); break;
        default:
          if (character < ' ')
            builder.Append("\\u").Append(((int)character).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
          else
            builder.Append(character);
          break;
      }
    }

    builder.Append('"');
    return builder.ToString();
  }
}
