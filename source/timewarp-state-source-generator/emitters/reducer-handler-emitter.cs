#region Purpose
// Emits the Handler a [Reducer] Action declares, for example CounterState.DecrementCountActionSet.Handler, which gets
// the state from the store and calls the action set's Reduce(state, action).
#endregion

#region Design
// Task 144, Option 3b (State half). A pure function of one ReducerHandlerModel, which ActionFactExtractor builds from
// the shared ReducerFacts rule on the same ActionFact the dispatch method uses, so there is no second scan.
// TimeWarp.Mediator 15.0.0-beta.5 dispatches the Action to this type because ReducerAttribute derives from
// GeneratedHandlerAttribute. Mediator registers it scoped and resolves it from the container, so the primary
// constructor takes IStore like a hand-written StateActionHandler.
// Every type name is global::-qualified, and Reduce is called through the action set, so a member named Action or
// Reduce on StateActionHandler or in the consumer's usings cannot capture the call.
// [GeneratedCode("TimeWarp.State.SourceGenerator", ...)] marks the type so ReducerFacts, run by the analyzer on the
// final compilation, does not mistake it for a hand-written handler of the same name.
#endregion

namespace TimeWarp.State.SourceGenerator;

internal static class ReducerHandlerEmitter
{
  public static void Emit(ReducerHandlerModel model, SourceProductionContext context) =>
    context.AddSource(model.HintName, GenerateHandlerCode(model));

  internal static string GenerateHandlerCode(ReducerHandlerModel model)
  {
    var builder = new StringBuilder();
    builder.AppendLine("// <auto-generated/>");
    builder.AppendLine("#nullable enable");
    builder.AppendLine();
    builder.AppendLine("#pragma warning disable CS1591");
    if (model.NamespaceName is not null)
    {
      builder.AppendLine($"namespace {model.NamespaceName};");
      builder.AppendLine();
    }

    string indent = string.Empty;
    foreach (string header in model.TypeHeaders)
    {
      builder.AppendLine($"{indent}{header}");
      builder.AppendLine($"{indent}{{");
      indent += "    ";
    }

    builder.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCode(\"{ReducerFacts.GeneratorToolName}\", \"1.0.0\")]");
    builder.AppendLine($"{indent}{model.Accessibility} sealed class {model.HandlerName}(global::TimeWarp.State.IStore store)");
    builder.AppendLine($"{indent}    : global::TimeWarp.State.StateActionHandler<{model.ActionType}>(store)");
    builder.AppendLine($"{indent}{{");
    builder.AppendLine($"{indent}    public override global::System.Threading.Tasks.ValueTask Handle");
    builder.AppendLine($"{indent}    (");
    builder.AppendLine($"{indent}        {model.ActionType} action,");
    builder.AppendLine($"{indent}        global::System.Threading.CancellationToken cancellationToken");
    builder.AppendLine($"{indent}    )");
    builder.AppendLine($"{indent}    {{");
    builder.AppendLine($"{indent}        {model.ActionSetType}.{ReducerFacts.ReduceMethodName}(Store.GetState<{model.StateType}>(), action);");
    builder.AppendLine($"{indent}        return default;");
    builder.AppendLine($"{indent}    }}");
    builder.AppendLine($"{indent}}}");

    for (int depth = model.TypeHeaders.Count - 1; depth >= 0; depth--)
    {
      indent = indent.Substring(0, depth * 4);
      builder.AppendLine($"{indent}}}");
    }

    builder.AppendLine("#pragma warning restore CS1591");
    return builder.ToString();
  }
}

internal sealed record ReducerHandlerModel
(
  string? NamespaceName,
  EquatableArray<string> TypeHeaders,
  string HandlerName,
  string Accessibility,
  string StateType,
  string ActionSetType,
  string ActionType,
  string HintName
);
